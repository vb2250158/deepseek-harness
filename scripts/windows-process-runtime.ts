/** Prepare local Windows Node copies with DSH process names and application icons. */
import { createHash } from 'node:crypto'
import { mkdir, readFile, rename, writeFile } from 'node:fs/promises'
import { isAbsolute, join, resolve } from 'node:path'
import { parseArgs } from 'node:util'
import { Data, NtExecutable, NtExecutableResource, Resource } from 'resedit'

/** Explicit source files and a new destination directory for Windows runtime copies. */
export interface WindowsProcessRuntimeOptions {
  /** Existing Node executable; its bytes remain unchanged. */
  node: string
  /** Existing DSH ICO containing the intended application sizes. */
  icon: string
  /** New directory; an existing directory is rejected rather than overwritten. */
  output: string
}

/** Executable identity read back from one generated runtime. */
export interface WindowsProcessRuntimeIdentity {
  /** Runtime role, independently selectable by its spawning owner. */
  role: 'host' | 'waimai'
  /** Generated executable's absolute path. */
  executable: string
  /** Task Manager's descriptive process name. */
  description: string
  /** SHA-256 of the generated bytes. */
  sha256: string
}

/** Source provenance and unsigned local runtime identities. */
export interface WindowsProcessRuntimeReceipt {
  /** Original Node input, retained for version and provenance checks. */
  source: { path: string; sha256: string; fileVersion: string; copyright: string }
  /** Existing icon input used for every generated role. */
  icon: { path: string; sha256: string }
  /** Resource changes produce unsigned copies; the original signature is not retained. */
  signature: 'unsigned-local-copy'
  /** Role-specific runtime files. */
  runtimes: WindowsProcessRuntimeIdentity[]
}

const identities = [
  { role: 'host', filename: 'dsh-host.exe', description: 'DSH 主服务' },
  { role: 'waimai', filename: 'dsh-waimai.exe', description: 'DSH 外卖工具' },
] as const

function sha256(bytes: Uint8Array): string {
  return createHash('sha256').update(bytes).digest('hex')
}

/**
 * Create role-specific Windows executables without changing the source or starting services.
 * Only a written manifest marks a complete output; failed output directories remain for diagnosis.
 * @param options - explicit source executable, icon and new output directory.
 * @returns input provenance and the generated runtime identities.
 * @throws when resource inputs are missing, output already exists, or publication fails.
 */
export async function prepareWindowsProcessRuntime(options: WindowsProcessRuntimeOptions): Promise<WindowsProcessRuntimeReceipt> {
  for (const [name, value] of [['node', options.node], ['icon', options.icon], ['output', options.output]] as const) {
    if (!isAbsolute(value)) throw new Error(`Windows process runtime: ${name} must be an absolute path`)
  }
  const source = await readFile(options.node)
  const iconBytes = await readFile(options.icon)
  const icon = Data.IconFile.from(iconBytes)
  if (icon.icons.length === 0) throw new Error('Windows process runtime: icon contains no images')
  const original = NtExecutableResource.from(NtExecutable.from(source, { ignoreCert: true }))
  const version = Resource.VersionInfo.fromEntries(original.entries)[0]
  const language = version?.getAllLanguagesForStringValues()[0]
  if (version === undefined || language === undefined) throw new Error('Windows process runtime: Node version resource is missing')
  const strings = version.getStringValues(language)
  if (!strings.FileVersion || !strings.LegalCopyright) throw new Error('Windows process runtime: Node version or copyright is missing')
  const receipt: WindowsProcessRuntimeReceipt = {
    source: { path: resolve(options.node), sha256: sha256(source), fileVersion: strings.FileVersion, copyright: strings.LegalCopyright },
    icon: { path: resolve(options.icon), sha256: sha256(iconBytes) },
    signature: 'unsigned-local-copy',
    runtimes: [],
  }
  await mkdir(options.output)
  for (const identity of identities) {
    const executable = NtExecutable.from(source, { ignoreCert: true })
    const resources = NtExecutableResource.from(executable)
    for (const info of Resource.VersionInfo.fromEntries(resources.entries)) {
      for (const translation of info.getAllLanguagesForStringValues()) {
        info.setStringValues(translation, {
          FileDescription: identity.description,
          ProductName: 'DeepSeek Harness',
          InternalName: identity.filename,
          OriginalFilename: identity.filename,
          Comments: 'Local DSH runtime copy based on Node.js; Node version and copyright are preserved.',
        })
      }
      info.outputToResourceEntries(resources.entries)
    }
    const groups = Resource.IconGroupEntry.fromEntries(resources.entries)
    if (groups.length === 0) throw new Error('Windows process runtime: Node icon group is missing')
    for (const group of groups) {
      Resource.IconGroupEntry.replaceIconsForResource(resources.entries, group.id, group.lang, icon.icons.map(item => item.data))
    }
    resources.outputResource(executable)
    const bytes = Buffer.from(executable.generate())
    const path = join(options.output, identity.filename)
    await writeFile(`${path}.tmp`, bytes, { flag: 'wx' })
    await rename(`${path}.tmp`, path)
    receipt.runtimes.push({ role: identity.role, executable: path, description: identity.description, sha256: sha256(bytes) })
  }
  await writeFile(join(options.output, 'manifest.json'), `${JSON.stringify(receipt, null, 2)}\n`, { flag: 'wx' })
  return receipt
}

if (import.meta.main) {
  const { values } = parseArgs({ options: { node: { type: 'string' }, icon: { type: 'string' }, output: { type: 'string' } } })
  if (!values.node || !values.icon || !values.output) {
    throw new Error('Usage: pnpm exec tsx scripts/windows-process-runtime.ts --node <absolute-node.exe> --icon <absolute.ico> --output <new-directory>')
  }
  console.log(JSON.stringify(await prepareWindowsProcessRuntime({ node: values.node, icon: values.icon, output: values.output }), null, 2))
}
